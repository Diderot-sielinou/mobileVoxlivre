import 'dart:math';

/// Nouvel identifiant de requête, UUID v4 (RFC 9562) tiré de [random]
/// (`Random.secure()` par défaut) : envoyé dans `x-request-id`, le backend
/// le reprend dans ses journaux (ADR-0004).
String newRequestId([Random? random]) {
  final source = random ?? Random.secure();
  final bytes = List<int>.generate(16, (_) => source.nextInt(256));
  bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // variante RFC
  final hex = bytes.map((b) => b.toRadixString(16).padLeft(2, '0')).join();
  return '${hex.substring(0, 8)}-${hex.substring(8, 12)}-'
      '${hex.substring(12, 16)}-${hex.substring(16, 20)}-${hex.substring(20)}';
}
